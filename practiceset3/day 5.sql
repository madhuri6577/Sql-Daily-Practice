-- 30. Display the customer name, order ID, and total value of each order.
-- Calculate order value by summing quantity × unit_price.
select c.customer_name , sum(oi.quantity*oi.unit_price),o.order_id 
from order_items oi
join orders o
on oi.order_id = o.order_id 
join customers c
on o.customer_id = c.customer_id
group by c.customer_name , o.order_id;

-- 31. Find the top 5 products by total revenue, sorted from highest to lowest.
select p.product_name , sum(oi.quantity*oi.unit_price) as total_revenue
from products p
join order_items oi
on p.product_id = oi.product_id
group by p.product_name
order by total_revenue desc
limit 5;

