-- 21. Display each customer's name and the total number of orders they placed. Include only customers who have placed at least one order.
select c.customer_name , count(o.order_id) 
from customers c
join orders o
on c.customer_id = o.customer_id
group by c.customer_name
having count(o.order_id) >= 1;

-- 22. Display every customer and the number of orders they placed, including customers with zero orders.
select c.customer_name , count(o.order_id) 
from customers c
left join orders o
on c.customer_id = o.customer_id
group by c.customer_name ;

-- 23. Find the total revenue generated by each product using products and order_items. 
-- Show the product name and total revenue.
select p.product_name , sum(oi.quantity*oi.unit_price) as total_revenue
from products p
join order_items oi
on p.product_id = oi.product_id
group by p.product_name;

-- 24. Find the total quantity sold for each product category by joining products and order_items.
select p.category , sum(oi.quantity) 
from products p
join order_items oi
on p.product_id = oi.product_id 
group by p.category;

