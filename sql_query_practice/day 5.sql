-- Q8.
-- Display all customers whose total spending is greater than the average customer spending.
-- ⚠️ Use: GROUP BY
-- Hint: First calculate spending for each customer, then compare it. (You may solve this after learning subqueries if needed.)
SELECT
    c.customer_id,
    c.customer_name,
    SUM(od.quantity * p.price) AS total_spending
FROM customers c
JOIN orders o
    ON c.customer_id = o.customer_id
JOIN order_details od
    ON o.order_id = od.order_id
JOIN products p
    ON od.product_id = p.product_id
GROUP BY c.customer_id, c.customer_name
HAVING SUM(od.quantity * p.price) >
(
    SELECT AVG(customer_spending)
    FROM
    (
        SELECT
            SUM(od.quantity * p.price) AS customer_spending
        FROM customers c
        JOIN orders o
            ON c.customer_id = o.customer_id
        JOIN order_details od
            ON o.order_id = od.order_id
        JOIN products p
            ON od.product_id = p.product_id
        GROUP BY c.customer_id
    ) AS spending
);
