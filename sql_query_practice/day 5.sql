-- Part A – Intermediate JOIN + GROUP BY
-- Q1.
-- Display each customer's total number of products purchased. Use: JOIN, SUM(quantity)
select sum(od.quantity),c.customer_name 
from order_details od
join orders o
on od.order_id = o.order_id
join customers c
on o.customer_id = c.customer_id
group by c.customer_name ;

-- Q2.
-- Display each customer's total spending. Use: JOIN, SUM(quantity × price)
select sum(od.quantity * p.price),c.customer_name 
from order_details od
join orders o
on od.order_id = o.order_id
join customers c
on o.customer_id = c.customer_id
join products p
on od.product_id = p.product_id
group by c.customer_name ;

-- Q3.
-- Display the top 5 products based on revenue. Use: JOIN, SUM(), ORDER BY
select sum(od.quantity * p.price) , p.product_name 
from order_details od
join products p
on od.product_id = p.product_id
group by p.product_name
order by sum(od.quantity * p.price) desc 
limit 5;

-- Q4.
-- Display the least-selling product. Use: SUM(quantity), ORDER BY
select sum(od.quantity ) , p.product_name 
from order_details od
join products p
on od.product_id = p.product_id
group by p.product_name
order by sum(od.quantity) 
limit 1;


-- Q5.
-- Display each category with its average product price and maximum product price. Use: AVG(), MAX()
select avg(p.price) as average_product_price ,max(p.price) as maximum_product_price , c.category_name 
from products p
join categories c
on p.category_id = c.category_id
group by category_name;

-- Q6.
-- Display the customer who placed the highest number of orders. Use: COUNT(), ORDER BY
