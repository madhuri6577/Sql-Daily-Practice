-- Q15.
-- Display each customer and show:
-- Total Quantity Purchased
-- Shopping Habit:
-- Heavy Buyer
-- Medium Buyer
-- Light Buyer
SELECT SUM(OD.QUANTITY) , C.CUSTOMER_NAME ,
CASE 
   WHEN SUM(OD.QUANTITY) >= 5 THEN 'HEAVY BUYER'
