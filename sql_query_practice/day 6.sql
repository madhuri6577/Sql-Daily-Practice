-- Part B – Revision Questions (Previous Concepts)
-- Q16.
-- Display the top 3 customers based on revenue.
SELECT SUM(OD.QUANTITY*P.PRICE) AS REVENUE, C.CUSTOMER_NAME
FROM ORDER_DETAILS OD 
JOIN PRODUCTS P
ON P.PRODUCT_ID = OD.PRODUCT_ID 
JOIN ORDERS O
ON O.ORDER_ID = OD.ORDER_ID
JOIN CUSTOMERS C
ON C.CUSTOMER_ID = O.CUSTOMER_ID
GROUP BY C.CUSTOMER_NAME 
ORDER BY SUM(OD.QUANTITY*P.PRICE) DESC
LIMIT 3;

-- Q17.
-- Display the product with the highest average quantity ordered.
SELECT ROUND(AVG(OD.QUANTITY),1) , P.PRODUCT_NAME 
FROM ORDER_DETAILS OD
JOIN PRODUCTS P
ON P.PRODUCT_ID = OD.PRODUCT_ID 
GROUP BY P.PRODUCT_NAME 
ORDER BY ROUND(AVG(OD.QUANTITY),1) DESC
LIMIT 1;

-- Q18.
-- Display each category's:
-- Total products
-- Average product price
-- Maximum product price
SELECT COUNT(P.PRODUCT_ID) AS TOTAL_PRODUCT , MAX(P.PRICE) AS MAXIMUM_PRICE , AVG(P.PRICE) AS AVERAGE_PRICE, C.CATEGORY_NAME
FROM CATEGORIES C 
JOIN PRODUCTS P
ON P.CATEGORY_ID  = C.CATEGORY_ID
GROUP BY C.CATEGORY_NAME;

-- Q19.
-- Display customers who purchased products from more than one category.
-- Hint: Use COUNT(DISTINCT category_id).
SELECT COUNT(DISTINCT CG.CATEGORY_ID) , C.CUSTOMER_NAME 
FROM ORDER_DETAILS OD 
JOIN PRODUCTS P
ON P.PRODUCT_ID = OD.PRODUCT_ID 
JOIN ORDERS O
ON O.ORDER_ID = OD.ORDER_ID
JOIN CUSTOMERS C
ON C.CUSTOMER_ID = O.CUSTOMER_ID
JOIN CATEGORIES CG
ON P.CATEGORY_ID = CG.CATEGORY_ID
GROUP BY C.CUSTOMER_NAME
HAVING  COUNT(DISTINCT CG.CATEGORY_ID) > 1;


-- Q20.
-- Display the month that generated the highest revenue.
-- Hint: Use:
-- EXTRACT(MONTH FROM order_date)
-- SUM(quantity × price)
-- GROUP BY
-- ORDER BY
SELECT SUM(OD.QUANTITY*P.PRICE) , EXTRACT(MONTH FROM O.ORDER_DATE)
FROM ORDER_DETAILS OD 
JOIN PRODUCTS P
ON P.PRODUCT_ID = OD.PRODUCT_ID 
JOIN ORDERS O
ON O.ORDER_ID = OD.ORDER_ID
GROUP BY  EXTRACT(MONTH FROM O.ORDER_DATE)
ORDER BY SUM(OD.QUANTITY*P.PRICE) DESC
LIMIT 1;
