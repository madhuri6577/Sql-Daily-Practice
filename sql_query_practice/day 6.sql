-- Q12.
-- Display each category's:
-- Number of products
-- Category Size:
-- Large
-- Medium
-- Small
-- (Create your own ranges.)
SELECT COUNT(DISTINCT P.PRODUCT_ID) , C.CATEGORY_NAME,
CASE 
   WHEN COUNT(DISTINCT P.PRODUCT_ID) > 5 THEN 'LARGE'
   WHEN COUNT(DISTINCT P.PRODUCT_ID) <=5 AND COUNT(DISTINCT P.PRODUCT_ID) > 3 THEN 'MEDIUM'
   ELSE 'SMALL'
   END AS CATEGORY_SIZES
FROM PRODUCTS P
JOIN CATEGORIES C
ON P.CATEGORY_ID = C.CATEGORY_ID 
JOIN ORDER_DETAILS OD
ON P.PRODUCT_ID = OD.PRODUCT_ID
GROUP BY C.CATEGORY_NAME ;
