-- Basic JOINs
-- Q1
-- Display the customer ID, customer city, and order ID for every order.
-- Use customers and orders.
select c.customer_id , c.customer_city ,o.order_id
from customers c
join orders o
on c.customer_id = o.customer_id;

-- Q2
-- Display:
-- order_id
-- customer_id
-- order_status
-- customer_city
-- customer_state
-- for all orders.
select o.order_id , c.customer_id ,o.order_status ,c.customer_city,c.customer_state
from orders o
join customers c
on o.customer_id = c.customer_id;

-- Q3
-- Display each order item along with the product category name.
-- Show:
-- order_id
-- product_id
-- price
-- product_category_name
select oi.order_id , p.product_id , oi.price , p.product_category_name
from order_items oi
join products p
on oi.product_id = p.product_id;

-- Q4
-- Display each order item along with the seller's city and state.
-- Show:
-- order_id
-- product_id
-- seller_id
-- seller_city
-- seller_state
select oi.order_id , oi.product_id , s.seller_id , s.seller_city , s.seller_state
from order_items oi
join sellers s
on oi.seller_id = s.seller_id;

-- Q5
-- Display all orders along with their payment type and payment value.
-- Show:
-- order_id
-- order_status
-- payment_type
-- payment_value
select o.order_id , o.order_status , op.payment_type , op.payment_value
from orders o
join order_payments op
on o.order_id = op.order_id;

-- 🟡 JOIN + WHERE
-- Q6
-- Find all delivered orders along with:
-- order_id
-- customer_id
-- customer_city
-- customer_state
select o.order_id , o.order_status , c.customer_id , c.customer_city , c.customer_state
from orders o
join customers c
on o.customer_id = c.customer_id
where o.order_status = 'delivered';

-- Q7
-- Find all order items for products belonging to the category:
-- bed_bath_table
-- Display:
-- order_id
-- product_id
-- price
-- product_category_name
select oi.order_id , p.product_id , oi.price , p.product_category_name
from order_items oi
