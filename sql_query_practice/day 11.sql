limit 10;

-- Q17
-- Find the number of delivered orders for each customer state.
-- Use:
-- customers → orders
-- Display:
-- customer_state
-- delivered_orders
-- Sort highest to lowest.
select count(o.order_id) as delivered_order , c.customer_state
from orders o
join customers c
on o.customer_id = c.customer_id
where o.order_status = 'delivered'
group by c.customer_state
order by delivered_order desc;

-- Q18
-- Find the average review score for each product category.
-- You'll need:
-- order_reviews → order_items → products
-- Display:
-- product_category_name
-- average_review_score
-- Sort highest to lowest.
select round(avg(ov.review_score),1) as average_review_score , p.product_category_name
from order_reviews ov
join order_items oi
on ov.order_id = oi.order_id
join products p
on oi.product_id = p.product_id
group by p.product_category_name 
order by average_review_score desc;

-- Q19 🔥
-- Find the top 10 sellers by total sales.
-- Use:
-- order_items → sellers
-- Display:
-- seller_id
-- seller_city
-- seller_state
-- total_sales
-- Sort highest to lowest.
select sum(oi.price) as total_sales , s.seller_id , s.seller_city ,s.seller_state 
