limit 10;

-- Q20 🔥 Challenge
-- Find the top 10 customer states by total payment value.
-- You'll need:
-- customers → orders → order_payments
-- Display:
-- customer_state
-- total_payment
-- Sort from highest to lowest.
select sum(op.payment_value) as total_payment , c.customer_state
from order_payments op
join orders o
on op.order_id = o.order_id 
join customers c
on o.customer_id = c.customer_id
group by c.customer_state
order by total_payment desc
limit 10;
