-- Q8
-- Find all orders placed by customers from São Paulo (SP).
-- Display:
-- order_id
-- customer_id
-- customer_city
-- order_status
select o.order_id ,c.customer_id , c.customer_city , o.order_status
from orders o
join customers c
on o.customer_id = c.customer_id 
where c.customer_state = 'SP';

-- Q9
-- Find all products sold by sellers from SP.
-- Display:
-- product_id
-- seller_id
-- seller_city
-- seller_state
select oi.product_id , s.seller_id , s.seller_city , s.seller_state
from order_items oi
join sellers s
on oi.seller_id = s.seller_id
where s.seller_state = 'SP';

-- 🟠 JOIN + GROUP BY
-- Q10
-- Find the number of orders placed by customers in each state.
-- Display:
-- customer_state
-- order_count
-- Sort from highest to lowest.
select count(o.order_id) as order_count , c.customer_state 
from orders o
join customers c
on o.customer_id = c.customer_id
group by c.customer_state
order by order_count desc;

-- Q11
-- Find the total sales generated by each product category.
-- Use price from order_items.
-- Display:
-- product_category_name
-- total_sales
-- Sort highest to lowest.
select sum(oi.price) as total_sales , p.product_category_name
from order_items oi
join products p
on oi.product_id = p.product_id
group by p.product_category_name
order by total_sales desc;

-- Q12
-- Find the total freight value generated by sellers in each state.
-- Display:
-- seller_state
-- total_freight
select sum(oi.freight_value) as total_freight , s.seller_state
from order_items oi
join sellers s
on oi.seller_id = s.seller_id
group by s.seller_state
order by total_freight desc;

-- Q13
-- Find the average order-item price for each product category.
-- Display:
-- product_category_name
-- average_price
-- Sort highest to lowest.
select round(avg(oi.price)) as avgerage_price , p.product_category_name
from order_items oi
join products p
on oi.product_id = p.product_id 
group by p.product_category_name
order by avgerage_price desc;


-- Q14
-- Find the number of order items sold by each seller.
-- Display:
-- seller_id
-- seller_city
-- items_sold
-- Sort highest to lowest.
-- Remember: there is no quantity column, so use COUNT(*).
select s.seller_id , s.seller_city , count(oi.order_id) as item_sold
from order_items oi
join sellers s
on oi.seller_id = s.seller_id
group by s.seller_id , s.seller_city
order by item_sold desc;

-- 🔥 Multi-table JOINs
-- Q15
-- Find the top 10 customer cities by total spending.
-- Use:
-- customers → orders → order_items
-- Calculate total spending using:
-- SUM(price)
-- Display:
-- customer_city
-- total_spending
select sum(oi.price) as total_spending ,c.customer_city
from order_items oi
join orders o
on oi.order_id = o.order_id 
join customers c
on o.customer_id = c.customer_id
group by c.customer_city
order by total_spending desc
limit 10;

-- Q16
